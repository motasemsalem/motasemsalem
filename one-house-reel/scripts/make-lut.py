# Writes src/grade/lut.ts: a 17³ teal-and-orange film LUT (S-curve, teal shadows, warm highlights, soft roll-off).
import numpy as np
N = 17
lines = ['TITLE "One House film"', f'LUT_3D_SIZE {N}']
for b in range(N):
    for g in range(N):
        for r in range(N):
            c = np.array([r, g, b]) / (N - 1)
            s = c * c * (3 - 2 * c)
            c = c + (s - c) * 0.38                       # contrast S-curve
            L = float(c @ [0.2126, 0.7152, 0.0722])
            c = c + np.array([-0.03, 0.012, 0.05]) * (1 - L) ** 2   # teal shadows
            c = c + np.array([0.055, 0.018, -0.045]) * L ** 2       # warm highlights
            L2 = float(c @ [0.2126, 0.7152, 0.0722])
            c = L2 + (c - L2) * 1.06                     # a touch more colour
            c = 0.018 + c * (0.965 - 0.018)              # lifted blacks, rolled whites
            lines.append(' '.join(f'{v:.5f}' for v in np.clip(c, 0, 1)))
open('src/grade/lut.ts', 'w').write('// Generated by scripts/make-lut.py.\nexport const FILM_LUT = `' + '\n'.join(lines) + '\n`;\n')
